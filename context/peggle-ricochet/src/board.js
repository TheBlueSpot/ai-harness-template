const ORANGE_IDS = new Set([
  1, 4, 6, 8, 10, 13, 16, 18, 21, 24, 26, 29, 32, 34,
]);

const PEG_LAYOUT = [
  [480, 140], [360, 180], [600, 180], [250, 210], [480, 220], [710, 210],
  [150, 260], [360, 270], [600, 275], [810, 260], [260, 325], [480, 330],
  [700, 325], [140, 390], [360, 390], [600, 390], [820, 390], [250, 450],
  [480, 460], [710, 450], [170, 520], [360, 545], [600, 545], [790, 520],
  [280, 605], [480, 620], [680, 605], [120, 175], [840, 175], [100, 320],
  [860, 320], [120, 470], [840, 470], [220, 575], [740, 575],
];

export function createBoard() {
  return PEG_LAYOUT.map(([x, y], index) => ({
    id: index,
    x,
    y,
    radius: 15,
    kind: ORANGE_IDS.has(index) ? "orange" : "blue",
    alive: true,
    pulse: Math.random() * Math.PI * 2,
  }));
}
